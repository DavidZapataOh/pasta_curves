#!/usr/bin/env python3
"""Generate the Lean transcription of the crate's inline AArch64 Pasta Montgomery blocks.

Reads the inline `asm!` blocks of `mul`, `square`, `add`, and `sub` in `src/asm/aarch64.rs`, and
writes

- `lean/PastaAArch64Asm/Transcription.lean`: each block as a Lean definition over the
  instruction semantics of `PastaAArch64Asm.Semantics`, one `let` per instruction, in the
  block's order, with the instruction as a trailing comment;
- `lean/PastaAArch64Asm/Vectors.lean`: one kernel-checked example per line of
  `test-vectors/pasta_mul-armv8-vectors.txt` whose operands are inside the proved
  contracts, the outputs of the real routines on an Apple M-series machine.

This file is the configuration: which blocks, which Lean modules, which vectors. The compiler
that does the work is the `asm2lean` package beside it (see its `__init__.py` for its stages).

The transcription is deliberately mechanical. The compiler's allocation of registers to the
operands is not modelled; a register that the block reads before it or an operand wrote it is
an error. A binding that nothing reads is not emitted: for an operand, the dropped binding is
left as a comment; for a carry flag, it is an ordinary unread flag write; for any other
computed register it would be dead code in the block, and is an error.

Run from the repository root:

    python3 lean/scripts/gen.py                  # write the two Lean files
    python3 lean/scripts/gen.py --skeleton NAME  # print the generated part of NAME's proof
    python3 lean/scripts/gen.py --check-spec lean/PastaAArch64Asm/Spec.lean

`lean/scripts/check.sh` regenerates and fails if the output differs from the committed files,
and checks that `Spec.lean` contains every block's skeleton verbatim once its
`-- BEGIN ... -- END` annotation blocks are removed. Python 3.10+; stdlib only.
"""
import sys
from pathlib import Path

from asm2lean.aarch64 import AArch64
from asm2lean.driver import LeanModule, Transcription, Vectors, main
from asm2lean.ir import Record
from asm2lean.lift import Block
from asm2lean.reroll import Loop, Role
from asm2lean.vectors import Field, Operation

LIMBS = ("l0", "l1", "l2", "l3")
LHS = Record("lhs", "Limbs", LIMBS, "hlhs")
RHS = Record("rhs", "Limbs", LIMBS, "hrhs")
VALUE = Record("value", "Limbs", LIMBS, "hv")
MODULUS = Record("modulus", "Limbs", LIMBS, "hm")

# `mul` was generated by Semolina's `pasta_mul-armv8.pl` as a prologue, one round body repeated
# three times, and an epilogue. The rounds differ only in the `rhs` limb they read.
MUL_ROUNDS = Loop(
    end="lsl t3,q,#62", count=3, operand="b{i}",
    round="mulMontRound",
    round_doc="One round of `mulMont`: the instructions between one `lsl t3,q,#62` and the next "
              "in each of its 3 rounds, on the round's `rhs` limb `b` and the registers `acc` "
              "carried from the previous round.",
    state="MulMontAcc", state_arg="acc", state_bound="hacc",
    param="b", param_bound="hb",
    value=("r0", "r1", "r2", "r3", "r4"),
    roles=(Role("r0", "r0", "accumulator limb 0"), Role("r1", "r1", "accumulator limb 1"),
           Role("r2", "r2", "accumulator limb 2"), Role("r3", "r3", "accumulator limb 3"),
           Role("r4", "r4", "accumulator limb 4"),
           Role("q", "q", "the round's Montgomery quotient `q`"),
           Role("t1", "t1", "`low(p1 * q)`, the first term of the round's reduction"),
           Role("t3", "t3", "`low(q * 2^62)`, the third term of the round's reduction")),
)

BLOCKS = (
    Block("mul", "mulMont",
          "The inline `asm!` block of `mul`: Montgomery multiplication, "
          "`lhs * rhs * 2^-256 mod p`, with the result in the block's output operands. Its "
          "rounds are those of Semolina's `mul_mont_pasta`; its epilogue keeps four limbs of "
          "the final candidate.",
          (LHS, RHS, MODULUS), MUL_ROUNDS),
    Block("square", "sqrMont",
          "The inline `asm!` block of `square`: Montgomery squaring, `value^2 * 2^-256 mod p`, "
          "the squaring loop body of Semolina's `sqr_n_mul_mont_pasta` followed by a "
          "conditional subtraction, with the result in the block's `inout` operands.",
          (VALUE, MODULUS)),
    Block("add", "addMod",
          "The inline `asm!` block of `add`: modular addition, `lhs + rhs mod p`, as a "
          "full-width addition, a subtraction of the modulus, and the selection of the reduced "
          "sum when that subtraction did not borrow, with the result in the block's `inout` "
          "operands.",
          (LHS, RHS, MODULUS)),
    Block("sub", "subMod",
          "The inline `asm!` block of `sub`: modular subtraction, `lhs - rhs mod p`, as a "
          "full-width subtraction and the addition of the modulus when it borrowed, with the "
          "result in the block's `inout` operands.",
          (LHS, RHS, MODULUS)),
)

TRANSCRIPTION = Transcription(
    source=Path("src/asm/aarch64.rs"),
    lifter=AArch64,
    scalars={"inv": "hinv_lt"},
    blocks=BLOCKS,
    module=LeanModule(
        path=Path("lean/PastaAArch64Asm/Transcription.lean"),
        header="""/-
Copyright Supranational LLC (the routines, transcribed from Semolina v0.1.4).
Copyright (c) 2026 the pasta-asm contributors (the transcription).
Released under the Apache License, Version 2.0, as described in the file LICENSE.
-/
""",
        imports=("PastaAArch64Asm.Semantics",),
        doc="""/-!
# The crate's inline Pasta field blocks, transcribed

GENERATED by `lean/scripts/gen.py` from the `asm!` blocks of `mul`, `square`, `add`, and `sub`
in `src/asm/aarch64.rs`; do not edit by hand. Each definition follows its block instruction by
instruction (the instruction is the trailing comment; the two lines that unpack an
instruction's (result, carry) pair are marked as its continuation), over the semantics of
`PastaAArch64Asm.Semantics`. Registers are rebound by the instructions that write them, `c`
is the carry flag, `s` is the (result, carry) pair of the instruction that last set both,
argument limbs are read where the block's operands bind them, and the output limbs are bound
where the block's output operands hold them. Bindings that nothing reads are left as
comments. See the generator's docstring for what it checks.
-/""",
        namespace="PastaAArch64Asm",
    ),
)


def mul_contract(p, operands):
    """A canonical left operand, or a canonical right operand whose limbs 1 to 3 are at most
    `2^64 - 3` (`mulMont_spec_of_lhs_lt`, `mulMont_spec_of_rhs_lt`)."""
    lhs, rhs = operands
    limbs = [(rhs >> (64 * i)) % 2**64 for i in range(1, 4)]
    return lhs < p or (rhs < p and all(limb <= 2**64 - 3 for limb in limbs))


def canonical(p, operands):
    return operands[0] < p


def anything(p, operands):
    return True


VECTORS = Vectors(
    source=Path("test-vectors/pasta_mul-armv8-vectors.txt"),
    # The crate's two fields, by the vectors file's key, as `Fields.lean` names them.
    fields={
        "Fp": Field("pallasBase",
                    0x40000000000000000000000000000000224698fc094cf91b992d30ed00000001),
        "Fq": Field("vestaBase",
                    0x40000000000000000000000000000000224698fc0994a8dd8c46eb2100000001),
    },
    operations={
        "MUL": Operation("mulMont", mul_contract),
        "SQR": Operation("sqrMont", canonical),
        "FROM": Operation("fromMont", anything),
    },
    module=LeanModule(
        path=Path("lean/PastaAArch64Asm/Vectors.lean"),
        header="""/-
Copyright (c) 2026 the pasta-asm contributors.
Released under the Apache License, Version 2.0, as described in the file LICENSE.
-/
""",
        imports=("PastaAArch64Asm.Compositions", "PastaAArch64Asm.Fields"),
        doc="""/-!
# Reference vectors for the transcribed blocks

GENERATED by `lean/scripts/gen.py` from `test-vectors/pasta_mul-armv8-vectors.txt`; do not
edit by hand. Each vector is the output of the real assembly (Semolina's `mul_mont_pasta`,
`sqr_mont_pasta`, and `from_mont_pasta`, as vendored by pasta_curves at
`8ad85e9fab7929f6236960e472f432a4bd9ccd74` and run on an Apple M-series machine) on the
given operands, and each example asks the kernel to evaluate the transcription on the same
operands. The multiplication and squaring examples exercise the inline blocks, which
transcribe those routines; the conversion examples exercise `fromMont`, the multiplication
block with `1` as its right operand, as the crate composes it. The vectors file also records
the routines' outputs on operands outside the proved contracts (unreduced operands), where the
block's dropped fifth limb can change the result, and those are left out here, with their
number recorded at the end.

The modulus limbs and `inv` are `pallasBase` and `vestaBase` from `Fields.lean`, the crate's
constants for its `Fp` (the Pallas base field) and `Fq` (the Vesta base field).
-/""",
        namespace="PastaAArch64Asm",
    ),
)

if __name__ == "__main__":
    sys.exit(main([TRANSCRIPTION], [VECTORS]))
